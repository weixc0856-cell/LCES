def render_outline_markdown(outline: ContentOutline, config: ProjectConfig) -> str:
    lines = [
        f"# 内容大纲（内部）：{outline.title}",
        "",
        f"- 项目：{config.project_id}",
        f"- 受众：{outline.audience or config.audience}",
        f"- 预计总时长：{outline.total_minutes} 分钟",
        "",
        "## 先修要求",
        "",
    ]
    lines += [f"- {item}" for item in outline.prerequisites] or ["- （无）"]
    for section in outline.sections:
        lines += [
            "",
            f"## {section.slide_id} {section.title}",
            "",
            f"预计时长：{section.estimated_minutes} 分钟",
            "",
            "学习目标：",
            *[f"- {item}" for item in section.learning_objectives],
            "",
            "关键要点：",
            *[f"- {item}" for item in section.key_points],
        ]
        if section.evidence_ids:
            lines += ["", f"证据：{', '.join(section.evidence_ids)}"]
        if section.visual_requirements:
            lines += ["", f"可视化需求：{'; '.join(section.visual_requirements)}"]
    lines.append("")
    return "\n".join(lines)


def render_script_markdown(
    script: SpeakerScript, outline: ContentOutline, config: ProjectConfig
) -> str:
    titles = {section.slide_id: section.title for section in outline.sections}
    minutes = script.total_estimated_seconds / 60
    lines = [
        f"# 完整口播稿（内部）：{config.title}",
        "",
        "> 内部工作资产。不得复制到公开 HTML、字幕或正式发布包，除非完成独立审核。",
        "",
        f"- 项目：{script.project_id}",
        f"- 预计时长：{minutes:.1f} 分钟"
        f"（按 {NARRATION_CHARS_PER_SECOND} 字/秒估算，非实测录音时长）",
        "",
    ]
    for section in script.sections:
        lines += [
            f"## {section.slide_id} {titles.get(section.slide_id, '')}",
            "",
            f"预计 {section.estimated_seconds} 秒",
            "",
            section.narration,
            "",
        ]
        if section.pronunciation_notes:
            lines += ["> 发音/术语提示：" + "；".join(section.pronunciation_notes), ""]
    if script.warnings:
        lines += ["## 生成警告", ""] + [f"- {item}" for item in script.warnings] + [""]
    return "\n".join(lines)
