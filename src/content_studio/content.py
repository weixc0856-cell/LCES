# Chinese narration pace used for estimates. It is an estimate, not a measured
# recording duration; the report states the method.
NARRATION_CHARS_PER_SECOND = 4.2

PUBLIC_MARKERS = (
    "TODO",
    "待核实",
    "口播稿",
    "讲者备注",
    "内部草稿",
    "内部 QA",
    "DRAFT ONLY",
)

OUTLINE_SYSTEM = """你是 LCES 的课程设计模块（tech-content-studio 第一部分）。
规则：
1. 只依据给定的研究简报与证据台账设计课程，不得引入未提供的事实。
2. 章节 slide_id 必须依次为 slide-001、slide-002……，不得跳号或重复。
3. evidence_ids 只能引用台账中存在的 evidence_id。
4. 课程深度与 target_duration_minutes 匹配，不得用重复内容凑时长。
5. 关键公式、图表与示例写入 visual_requirements，供后续场景与图表阶段使用。
6. total_minutes 应与各章节 estimated_minutes 之和一致，并接近目标时长。
只输出符合给定 JSON Schema 的 JSON。"""

SOURCE_ID_PATTERN = re.compile(r"^source-[a-z0-9-]+$")


PUBLIC_SYSTEM = """你是 LCES 的公开内容生成模块（tech-content-studio 第二部分）。
公开展示内容规则：
1. 只写适合公开页面展示的正式正文，不得包含口播稿、讲者备注、草稿、QA 记录或调试信息。
2. 不得出现 TODO、待核实、占位、内部讨论等内部工作标记。
3. 不得写入 API 密钥、内部路径或任何系统提示词内容。
4. 科学限制、假设与不确定性可以作为正式内容表述，但必须措辞严谨。
5. 每个 slide 的 slide_id 必须与大纲完全一致，顺序一致。
6. source_ids 只能填写来源台账中存在的 source_id（形如 source-001）。禁止填写
   evidence-xxx、claim-xxx 等内部编号；内部证据台账不进入公开页。
7. 正文应完整支持目标受众理解，不使用空泛填充。
8. 只有 content/ 下已存在对应文件时才能使用 figure 块；模型不能创建图片，
   没有现成图表就改用表格或文字说明。
9. 流程图与时序图使用 diagram 块，mermaid 字段只写 Mermaid 源码；不要写 HTML、
   脚本、click 指令或 %%{init}%% 配置块。关系图可用 graph 块，dot 字段只写 DOT 源码。
只输出符合给定 JSON Schema 的 JSON。"""

SCRIPT_SYSTEM = """你是 LCES 的内部口播稿模块（tech-content-studio 第三部分）。
规则：
1. 这是内部录音准备材料，不会出现在公开 HTML 中；可以写口语化表达、过渡和演示提示。
2. 必须覆盖大纲中的每一个 slide_id，且只覆盖这些 slide_id。
3. 讲稿内容必须与公开内容一致，不得引入未核验的新事实。
4. 对专有名词、数字和可能读错的术语，写入 pronunciation_notes。
5. 不得把假设或推测写成确定结论。
只输出符合给定 JSON Schema 的 JSON。"""

READING_SYSTEM = """你是 LCES 的研究阅读版模块（tech-content-studio 第四部分）。
规则：
1. 阅读版面向课后深入阅读，可比展示页更密集，但不得包含口播稿或内部备注。
2. slide_id 必须与大纲完全一致。
3. 所有关键结论保留 source_ids 引用；source_ids 只能是 source-xxx，
   不得使用 evidence-xxx 或 claim-xxx。
4. references 只能列出真实来源台账中的条目。
只输出符合给定 JSON Schema 的 JSON。"""


def estimate_narration_seconds(text: str) -> int:
    return max(20, round(len(text) / NARRATION_CHARS_PER_SECOND))


def _compact_json(payload: object, limit: int = 30_000) -> str:
    return truncate(json.dumps(payload, ensure_ascii=False, default=str), limit)


def _evidence_table(ledger: EvidenceLedger, limit: int = 12_000) -> str:
    lines = ["evidence_id | claim_id | source_id | 关系 | 核验 | 摘录"]
    for record in ledger.records:
        excerpt = record.source_excerpt.replace("\n", " ")[:160]
        lines.append(
            f"{record.evidence_id} | {record.claim_id} | {record.source_id} |"
            f" {record.support_relation} | {record.verification_status} | {excerpt}"
        )
    return truncate("\n".join(lines), limit)


def _source_ids(registry: SourceRegistry | None) -> list[str]:
    return [source.source_id for source in registry.sources] if registry else []


def generate_outline(
    project_dir: Path,
    config: ProjectConfig,
    brief: ResearchBrief,
    ledger: EvidenceLedger,
    provider: ModelProvider,
    *,
    max_output_tokens: int | None = None,
) -> ContentOutline:
    prompt = (
        f"项目: {config.title}（{config.project_id}）\n"
        f"任务类型: {config.content_mode}\n"
        f"受众: {config.audience}\n"
        f"语言: {config.language}\n"
        f"目标时长: {config.target_duration_minutes} 分钟\n\n"
        "研究简报:\n"
        f"{_compact_json(brief.model_dump(mode='json'))}\n\n"
        "证据台账:\n"
        f"{_evidence_table(ledger)}"
    )
    request = GenerationRequest(
        messages=[Message("system", OUTLINE_SYSTEM), Message("user", prompt)],
        max_tokens=max_output_tokens or DEFAULT_MAX_TOKENS,
        metadata={
            "project_id": config.project_id,
            "title": config.title,
            "evidence_ids": ",".join(record.evidence_id for record in ledger.records),
            "stage": "outline",
        },
    )
    outline = provider.generate_structured(request, ContentOutline)
    if outline.project_id != config.project_id:
        outline = outline.model_copy(update={"project_id": config.project_id})
    if not any(section.evidence_ids for section in outline.sections) and ledger.records:
        raise ValidationFailure(
            "outline cites no evidence although the ledger has records; refusing to continue"
        )

    write_json(project_dir / "content" / "outline.json", outline)
    write_text(
        project_dir / "internal" / "content_outline.md",
        render_outline_markdown(outline, config),
    )
    _trace(project_dir, "outline", provider, "ContentOutline")
    return outline


def generate_public_content(
    project_dir: Path,
    config: ProjectConfig,
    outline: ContentOutline,
    ledger: EvidenceLedger,
    registry: SourceRegistry,
    provider: ModelProvider,
    *,
    max_output_tokens: int | None = None,
) -> PublicContent:
    prompt = (
        f"项目: {config.title}（{config.project_id}）\n"
        f"语言: {config.language}\n"
        f"受众: {config.audience}\n\n"
        "课程大纲:\n"
        f"{_compact_json(outline.model_dump(mode='json'))}\n\n"
        "内部证据台账（仅供理解，不要把 evidence-xxx 写入 source_ids）:\n"
        f"{_evidence_table(ledger)}\n\n"
        "可用 source_id（公开页只能从这里选择）:\n"
        f"{', '.join(_source_ids(registry))}\n\n"
        "请为每个大纲章节生成公开展示正文。"
    )
    request = GenerationRequest(
        messages=[Message("system", PUBLIC_SYSTEM), Message("user", prompt)],
        max_tokens=max_output_tokens or DEFAULT_MAX_TOKENS,
        metadata={
            "project_id": config.project_id,
            "title": config.title,
            "source_ids": ",".join(_source_ids(registry)),
            "stage": "public_content",
        },
    )
    content = provider.generate_structured(request, PublicContent)
    content = content.model_copy(
        update={"project_id": config.project_id, "title": config.title, "language": config.language}
    )

    expected = [section.slide_id for section in outline.sections]
    actual = [slide.slide_id for slide in content.slides]
    if actual != expected:
        raise ValidationFailure(
            "public content slide_id/order does not match the outline: "
            f"expected {expected}, got {actual}"
        )

    text = json.dumps(content.model_dump(mode="json"), ensure_ascii=False)
    for marker in PUBLIC_MARKERS:
        if marker.lower() in text.lower():
            raise ValidationFailure(
                f"public content contains internal marker '{marker}'; generation rejected"
            )

    # Structural boundary, not just a prompt hint: a public citation must be
    # a well-formed source id that exists in the public registry. Internal
    # evidence/claim ids (evidence-001, claim-001) fail on the pattern even if
    # someone registered such an id by mistake.
    known_sources = set(_source_ids(registry))
    unknown = {
        source_id
        for slide in content.slides
        for source_id in slide.source_ids
        if not SOURCE_ID_PATTERN.fullmatch(source_id) or source_id not in known_sources
    }
    if unknown:
        raise ValidationFailure(
            "public content cites unknown source ids: " + ", ".join(sorted(unknown))
        )

    content, dropped_figures = _drop_missing_figures(project_dir, content)

    write_json(project_dir / "content" / "public_content.json", content)
    _trace(
        project_dir,
        "public_content",
        provider,
        "PublicContent",
        extra={"dropped_figures": dropped_figures} if dropped_figures else None,
    )
    return content


def generate_speaker_script(
    project_dir: Path,
    config: ProjectConfig,
    outline: ContentOutline,
    ledger: EvidenceLedger,
    provider: ModelProvider,
    *,
    max_output_tokens: int | None = None,
) -> SpeakerScript:
    prompt = (
        f"项目: {config.title}（{config.project_id}）\n"
        f"语言: {config.language}\n"
        f"目标时长: {config.target_duration_minutes} 分钟\n\n"
        "课程大纲:\n"
        f"{_compact_json(outline.model_dump(mode='json'))}\n\n"
        "证据台账:\n"
        f"{_evidence_table(ledger)}\n\n"
        "请为每个章节写完整口播稿。"
    )
    request = GenerationRequest(
        messages=[Message("system", SCRIPT_SYSTEM), Message("user", prompt)],
        max_tokens=max_output_tokens or DEFAULT_MAX_TOKENS,
        metadata={
            "project_id": config.project_id,
            "title": config.title,
            "stage": "speaker_script",
        },
    )
    script = provider.generate_structured(request, SpeakerScript)
    expected = [section.slide_id for section in outline.sections]
    actual = [section.slide_id for section in script.sections]
    if actual != expected:
        raise ValidationFailure(
            "speaker script does not map one-to-one to the outline: "
            f"expected {expected}, got {actual}"
        )

    sections = [
        section.model_copy(
            update={"estimated_seconds": estimate_narration_seconds(section.narration)}
        )
        for section in script.sections
    ]
    script = script.model_copy(
        update={
            "project_id": config.project_id,
            "language": config.language,
            "sections": sections,
            "total_estimated_seconds": sum(item.estimated_seconds for item in sections),
        }
    )

    write_json(project_dir / "internal" / "speaker_script.json", script)
    write_text(
        project_dir / "internal" / "speaker_script.md",
        render_script_markdown(script, outline, config),
    )
    _trace(project_dir, "speaker_script", provider, "SpeakerScript")
    return script


