def _project_id(request: GenerationRequest) -> str:
    return request.metadata.get("project_id", "example-course")


def _title(request: GenerationRequest) -> str:
    return request.metadata.get("title", "示例课程（MOCK）")


def _source_ids(request: GenerationRequest) -> list[str]:
    raw = request.metadata.get("source_ids", "")
    identifiers = [item.strip() for item in raw.split(",") if item.strip()]
    return identifiers or ["source-001"]


def _evidence_ids(request: GenerationRequest) -> list[str]:
    raw = request.metadata.get("evidence_ids", "")
    return [item.strip() for item in raw.split(",") if item.strip()]


